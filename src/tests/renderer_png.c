static void decoded_cache(void) {
    byte *pixels, changed[sizeof(rgb_png) + 1];
    int width, height, i;
    ri.Cvar_Get = cache_cvar;
    cache_setting.integer = 1;
    source = rgb_png; sourceSize = sizeof(rgb_png);
    R_LoadPNG("cached.png", &pixels, &width, &height);
    assert(pixels && pngDecodeCacheCount == 1 && pngDecodeCacheBytes > 0);
    assert(!memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    pixels[0] ^= 255; /* A caller must not mutate the cached canonical pixels. */
    release(pixels);
    R_LoadPNG("alias.png", &pixels, &width, &height);
    assert(pixels && pngDecodeCacheCount == 1 && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    release(pixels);
    /* Same path/length, different compressed bytes: reject the damaged stream,
     * rather than returning the previously admitted source's cached result. */
    memcpy(changed, rgb_png, sizeof(rgb_png));
    changed[sizeof(rgb_png) - 12 - 5] ^= 1;
    source = changed;
    R_LoadPNG("cached.png", &pixels, &width, &height);
    assert(!pixels && !width && !height && !allocations);
    source = rgb_png;
    R_LoadPNG("cached.png", &pixels, &width, &height);
    assert(pixels && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    release(pixels);
    cache_setting.integer = 0;
    R_LoadPNG("disabled.png", &pixels, &width, &height);
    assert(pixels && !pngDecodeCacheCount && !pngDecodeCacheBytes);
    release(pixels);
    assert(!PNG_Retain(rgb_png, sizeof(rgb_png), (byte *)rgb_rgba, 3, 2, 1));
    /* Distinct valid inputs with ignored trailing bytes cannot grow the cache
     * past its fixed entry bound. Their rendered pixels remain identical. */
    cache_setting.integer = 1;
    memcpy(changed, rgb_png, sizeof(rgb_png));
    source = changed; sourceSize = sizeof(changed);
    for (i = 0; i < 32; ++i) {
        changed[sizeof(rgb_png)] = i;
        R_LoadPNG("capacity.png", &pixels, &width, &height);
        assert(pixels && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
        release(pixels);
        assert(pngDecodeCacheCount <= ARRAY_LEN(pngDecodeCache));
        assert(pngDecodeCacheBytes <= 1u << 20);
    }
    R_ClearPNGCache();
    assert(!pngDecodeCacheCount && !pngDecodeCacheBytes && !allocations);
    ri.Cvar_Get = NULL;
}
static void cached_preparation(void) {
    dkImageBatch_t *batch;
    byte *pixels, changed[sizeof(rgb_png)];
    unsigned decoded;
    int width, height;
    ri.Cvar_Get = cache_cvar;
    cache_setting.integer = 1;
    permit_read = 1;
    source = rgb_png; sourceSize = sizeof(rgb_png);
    decoded = prepared_decodes;
    batch = R_CreateCachedImageBatch(1);
    assert(batch && R_QueuePNG(batch, "prepared-cache.png"));
    assert(await_batch(batch) == 1 && prepared_decodes == decoded + 1);
    assert(pngDecodeCacheCount == 1 && !readers);
    R_FreeImageBatch(batch);
    assert(!allocations);

    decoded = prepared_decodes;
    batch = R_CreateCachedImageBatch(1);
    assert(batch && R_QueuePNG(batch, "prepared-alias.png"));
    assert(await_batch(batch) == 1 && prepared_decodes == decoded);
    /* Cache resize must not invalidate a completed batch's independent copy. */
    cache_setting.integer = 0;
    R_ClearPNGCache();
    R_SelectImageBatch(batch);
    R_LoadPNG("prepared-alias.png", &pixels, &width, &height);
    assert(pixels && width == 3 && height == 2 && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    pixels[0] ^= 255;
    release(pixels);
    R_LoadPNG("prepared-alias.png", &pixels, &width, &height);
    assert(pixels && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    release(pixels);
    R_FreeImageBatch(batch);
    assert(!allocations && !readers && !pngDecodeCacheCount);

    cache_setting.integer = 1;
    source = rgb_png;
    batch = R_CreateCachedImageBatch(1);
    assert(batch && R_QueuePNG(batch, "valid.png") && await_batch(batch) == 1);
    R_FreeImageBatch(batch);
    memcpy(changed, rgb_png, sizeof(changed));
    changed[sizeof(changed) - 12 - 5] ^= 1;
    source = changed;
    batch = R_CreateCachedImageBatch(1);
    assert(batch && R_QueuePNG(batch, "valid.png") && await_batch(batch) == -1);
    R_FreeImageBatch(batch);
    assert(!allocations && !readers && pngDecodeCacheCount == 1);

    source = rgb_png;
    batch = R_CreateCachedImageBatch(1);
    assert(batch && R_QueuePNG(batch, "budget.png"));
    batch->bytes = DK3_MATERIAL_PIXEL_BUDGET - 1;
    assert(await_batch(batch) == -1);
    R_FreeImageBatch(batch);
    R_ClearPNGCache();
    ri.Cvar_Get = NULL;
    assert(!allocations && !readers);
}

static void borrowed_preparation(void) {
    dkImageBatch_t *a, *b;
    const byte *view = NULL, *other = NULL;
    byte *copy;
    int width = -1, height = -1, before_reads, before_allocations;
    assert(!R_BorrowPreparedPNG("view.png", &view, &width, &height));
    assert(!view && !width && !height);
    source = rgb_png; sourceSize = sizeof(rgb_png); permit_read = 1;
    a = R_CreateImageBatch(1);
    assert(a && R_QueuePNG(a, "view.png"));
    R_SelectImageBatch(a);
    assert(!R_BorrowPreparedPNG("view.png", &view, &width, &height));
    assert(await_batch(a) == 1);
    before_reads = reads; before_allocations = allocations;
    sourceSize = 1; /* A view must not re-read/decode source or allocate RI memory. */
    assert(R_BorrowPreparedPNG("view.png", &view, &width, &height));
    assert(view == a->images[0].pixels && width == 3 && height == 2);
    assert(!memcmp(view, rgb_rgba, sizeof(rgb_rgba)));
    assert(reads == before_reads && allocations == before_allocations);
    assert(!R_BorrowPreparedPNG(NULL, &other, NULL, NULL) && !other);
    assert(!R_BorrowPreparedPNG("missing.png", &other, NULL, NULL) && !other);
    assert(!R_BorrowPreparedPNG("view.png", NULL, NULL, NULL));
    /* Existing owned callers remain independent and aliases can repeatedly
     * read the immutable batch. Their mutation/free must not alter the view. */
    assert(R_TakePreparedPNG("view.png", &copy, &width, &height));
    assert(copy != view && !memcmp(copy, view, sizeof(rgb_rgba)));
    copy[0] ^= 255;
    assert(!memcmp(view, rgb_rgba, sizeof(rgb_rgba)));
    release(copy);
    assert(R_BorrowPreparedPNG("view.png", &other, NULL, NULL) && other == view);
    source = palette_png; sourceSize = sizeof(palette_png);
    b = R_CreateImageBatch(1);
    assert(b && R_QueuePNG(b, "other.png") && await_batch(b) == 1);
    R_SelectImageBatch(b);
    assert(R_BorrowPreparedPNG("other.png", &other, &width, &height));
    assert(width == 3 && height == 1 && !memcmp(other, palette_rgba, sizeof(palette_rgba)));
    assert(!memcmp(view, rgb_rgba, sizeof(rgb_rgba)));
    R_FreeImageBatch(b);
    assert(!R_BorrowPreparedPNG("view.png", &other, NULL, NULL) && !other);
    assert(!memcmp(view, rgb_rgba, sizeof(rgb_rgba)));
    R_FreeImageBatch(a);
    sourceSize = 20;
    a = R_CreateImageBatch(1);
    assert(a && R_QueuePNG(a, "failed.png") && await_batch(a) == -1);
    R_SelectImageBatch(a);
    assert(!R_BorrowPreparedPNG("failed.png", &other, &width, &height));
    assert(!other && !width && !height);
    R_FreeImageBatch(a);
    assert(!allocations && !readers && !selectedBatch);
}

static void preparation_exclusions(void) {
    dkImageBatch_t *earlier = R_CreateImageBatch(1), *later = R_CreateImageBatch(2);
    byte *pixels;
    int width, height;
    assert(earlier && later && R_QueuePNG(earlier, "shared.png"));
    assert(R_ExcludePreparedImages(later, earlier));
    assert(later->excluded && later->excludedCount == 1);
    assert((void *)later->excluded != (void *)earlier->images[0].name);
    R_FreeImageBatch(earlier); /* The name snapshot must survive its source. */
    assert(R_QueuePNG(later, "shared.png") && later->count == 0);
    assert(R_QueuePNG(later, "other.png") && later->count == 1);
    source = rgb_png; sourceSize = sizeof(rgb_png); permit_read = 1;
    assert(await_batch(later) == 1 && !later->excluded && !later->excludedCount);
    R_SelectImageBatch(later);
    /* The earlier hint never registered a texture: actual loading still reads
     * and validates the excluded source through the ordinary owner path. */
    R_LoadPNG("shared.png", &pixels, &width, &height);
    assert(pixels && width == 3 && height == 2 && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    release(pixels);
    sourceSize = 1;
    R_LoadPNG("other.png", &pixels, &width, &height);
    assert(pixels && !memcmp(pixels, rgb_rgba, sizeof(rgb_rgba)));
    release(pixels);
    R_FreeImageBatch(later);
    assert(!allocations && !readers);

    earlier = R_CreateImageBatch(1);
    assert(earlier && R_QueuePNG(earlier, "shared.png") && await_batch(earlier) == -1);
    later = R_CreateImageBatch(1);
    assert(later && R_ExcludePreparedImages(later, earlier));
    assert(R_QueuePNG(later, "shared.png") && later->count == 1);
    R_FreeImageBatch(earlier);
    sourceSize = sizeof(rgb_png);
    assert(await_batch(later) == 1);
    R_FreeImageBatch(later);
    assert(!allocations && !readers);
}

static void multiple_preparation_exclusions(void) {
    dkImageBatch_t *a = R_CreateImageBatch(1), *b = R_CreateImageBatch(1), *later = R_CreateImageBatch(1);
    unsigned i;
    assert(a && b && later);
    assert(R_QueuePNG(a, "first.png") && R_QueuePNG(b, "second.png"));
    assert(R_ExcludePreparedImages(later, a) && R_ExcludePreparedImages(later, b));
    assert(later->excludedCount == 2);
    R_FreeImageBatch(a); R_FreeImageBatch(b);
    assert(R_QueuePNG(later, "first.png") && R_QueuePNG(later, "second.png") && later->count == 0);
    R_FreeImageBatch(later); /* Cancel before dispatch, including both snapshots. */

    a = R_CreateImageBatch(1024); later = R_CreateImageBatch(1);
    assert(a && later);
    for (i = 0; i < 1024; ++i) {
        char name[MAX_QPATH];
        snprintf(name, sizeof(name), "resource-%u.png", i);
        assert(R_QueuePNG(a, name));
    }
    for (i = 0; i < 4; ++i) assert(R_ExcludePreparedImages(later, a));
    assert(later->excludedCount == DK3_PREPARATION_EXCLUSION_NAMES);
    assert(!R_ExcludePreparedImages(later, a));
    assert(later->excludedCount == DK3_PREPARATION_EXCLUSION_NAMES);
    R_FreeImageBatch(a);
    assert(R_QueuePNG(later, "resource-1023.png") && later->count == 0);
    assert(R_ExcludePreparedImages(later, NULL) && !later->excluded && !later->excludedCount);
    R_FreeImageBatch(later);
    assert(!allocations && !readers);
}

